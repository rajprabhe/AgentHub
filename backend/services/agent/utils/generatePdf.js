import PDFDocument from "pdfkit";

export const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margin: 50,
        bufferPages: true,
        info: {
          Author: "AgentHub",
          Title: data.title,
          Creator: "AgentHub",
        },
      });

      const chunks = [];

      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      // Title
      doc
        .fillColor("#111827")
        .font("Helvetica-Bold")
        .fontSize(26)
        .text(data.title || "Generated Document", {
          align: "center",
        });

      // Subtitle
      if (data.subtitle) {
        doc.moveDown(0.5);

        doc
          .fillColor("#6B7280")
          .font("Helvetica")
          .fontSize(13)
          .text(data.subtitle, {
            align: "center",
          });
      }

      doc.moveDown(2);

      // Sections
      for (const section of data.sections || []) {
        doc
          .fillColor("#111827")
          .font("Helvetica-Bold")
          .fontSize(17)
          .text(section.heading || "Section");

        doc.moveDown(0.5);

        for (const point of section.points || []) {
          doc
            .fillColor("#374151")
            .font("Helvetica")
            .fontSize(11)
            .text(`•  ${point}`, {
              indent: 10,
              paragraphGap: 5,
              lineGap: 3,
            });

          doc.moveDown(0.3);
        }

        doc.moveDown();
      }

      // Footer
      doc
        .fillColor("#9CA3AF")
        .font("Helvetica")
        .fontSize(9)
        .text("Generated by AgentHub", {
          align: "center",
        });

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};
